// Regenerates assets/patterns/*.svg — the brand's dot-field textures.
//
// CANONICAL RECIPE (landed 2026-08-08; tuned in lab/textures.html):
//   {"pattern":"dots","seed":5994,"cell":14,"szmin":0,"szmax":4,
//    "amin":0,"amax":0.105,"cluster":6,"detail":0.5,"cut":0}
//
// The SVGs carry explicit width/height so they render at a FIXED intrinsic
// scale (background-size:auto) — dot size never varies with the height of
// the section that wears the field.
//
// The field always ramps right-to-left: densest at the right edge, the
// last, smallest dots landing around the middle of the page. A bottom fade
// dissolves the field if a section is taller than the asset.
//
// The noise code below is a copy of lab/textures.html's — keep them in
// sync, or a re-tuned recipe will not reproduce. Run: node build-patterns.mjs

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const INK = '#002147';
const RECIPE = {
  seed: 5994, cell: 14, szmin: 0, szmax: 4,
  amin: 0, amax: 0.105, cluster: 6, detail: 0.5, cut: 0,
};

// Periodic value noise: the grid wraps, so a field sampled on [0,1) tiles
// seamlessly. Used for the universal ground cut.
function makeNoiseTile(seed, g) {
  let s = (seed >>> 0) || 1;
  const rnd = () => { s ^= s << 13; s >>>= 0; s ^= s >> 17; s ^= s << 5; s >>>= 0; return s / 4294967296; };
  const grid = [];
  for (let y = 0; y < g; y++) { const row = []; for (let x = 0; x < g; x++) row.push(rnd()); grid.push(row); }
  const sm = t => t * t * (3 - 2 * t);
  return (u, v) => {
    const x = (u % 1) * g, y = (v % 1) * g, xi = x | 0, yi = y | 0;
    const xf = sm(x - xi), yf = sm(y - yi);
    const x2 = (xi + 1) % g, y2 = (yi + 1) % g;
    const a = grid[yi][xi] * (1 - xf) + grid[yi][x2] * xf;
    const b = grid[y2][xi] * (1 - xf) + grid[y2][x2] * xf;
    return a * (1 - yf) + b * yf;
  };
}

function makeNoise(seed, gw, gh) {
  let s = (seed >>> 0) || 1;
  const rnd = () => { s ^= s << 13; s >>>= 0; s ^= s >> 17; s ^= s << 5; s >>>= 0; return s / 4294967296; };
  const grid = [];
  for (let y = 0; y <= gh; y++) { const row = []; for (let x = 0; x <= gw; x++) row.push(rnd()); grid.push(row); }
  const sm = t => t * t * (3 - 2 * t);
  return (u, v) => {
    u = Math.min(Math.max(u, 0), 0.999); v = Math.min(Math.max(v, 0), 0.999);
    const x = u * gw, y = v * gh, xi = x | 0, yi = y | 0, xf = sm(x - xi), yf = sm(y - yi);
    const a = grid[yi][xi] * (1 - xf) + grid[yi][xi + 1] * xf;
    const b = grid[yi + 1][xi] * (1 - xf) + grid[yi + 1][xi + 1] * xf;
    return a * (1 - yf) + b * yf;
  };
}
const smoothstep = (e0, e1, x) => { const t = Math.min(Math.max((x - e0) / (e1 - e0), 0), 1); return t * t * (3 - 2 * t); };

function dots(p, W, H, { rampStart = null, rampEnd = null, bottomFade = true } = {}) {
  const n1 = makeNoise(p.seed, p.cluster, Math.max(2, Math.round(p.cluster * H / W)));
  const n2 = makeNoise(p.seed + 999, p.cluster * 2 + 1, Math.max(3, Math.round((p.cluster * 2 + 1) * H / W)));
  const lerp = (a, b, t) => a + (b - a) * t;
  const el = [];
  for (let y = p.cell / 2; y < H; y += p.cell) {
    for (let x = p.cell / 2; x < W; x += p.cell) {
      const u = x / W, v = y / H;
      let t = (1 - p.detail) * n1(u, v) + p.detail * n2(u, v);
      if (rampStart !== null) t *= smoothstep(rampStart, rampEnd, u);
      if (bottomFade) t *= 1 - smoothstep(0.86, 1, v);
      t = Math.min(Math.max(t, 0), 1);
      if (t <= p.cut) continue;
      const r = lerp(p.szmin, p.szmax, t), a = lerp(p.amin, p.amax, t);
      if (r < 0.3 || a < 0.008) continue; // invisible at screen scale
      el.push(`<circle cx="${x}" cy="${y}" r="${r.toFixed(2)}" fill="${INK}" opacity="${a.toFixed(3)}"/>`);
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">` +
    `<!-- generated by lab/tools/build-patterns.mjs · recipe ${JSON.stringify(RECIPE)} -->` +
    el.join('') + '</svg>';
}

// The right cut ships as a numbered set differing ONLY in seed. Adjacent
// placements rotate through the set so no two visible fields ever repeat.
// SEEDS[0] is the canonical recipe seed; the rest are fixed companions.
const SEEDS = [5994, 1387, 2718, 3141, 4669, 8128];

// The universal ground cut: seamless tile, quieter than the plate field
// (alpha capped at 0.055) so it may sit under any content as paper grain.
function groundTile(p, W) {
  const n1 = makeNoiseTile(p.seed, p.cluster);
  const n2 = makeNoiseTile(p.seed + 999, p.cluster * 2);
  const lerp = (a, b, t) => a + (b - a) * t;
  const el = [];
  for (let y = p.cell / 2; y < W; y += p.cell) {
    for (let x = p.cell / 2; x < W; x += p.cell) {
      let t = (1 - p.detail) * n1(x / W, y / W) + p.detail * n2(x / W, y / W);
      t = Math.min(Math.max(t, 0), 1);
      const r = lerp(p.szmin, p.szmax * 0.85, t), a = lerp(0, 0.055, t);
      if (r < 0.3 || a < 0.008) continue;
      el.push(`<circle cx="${x}" cy="${y}" r="${r.toFixed(2)}" fill="${INK}" opacity="${a.toFixed(3)}"/>`);
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${W}" viewBox="0 0 ${W} ${W}">` +
    `<!-- generated by lab/tools/build-patterns.mjs · seamless ground tile · recipe ${JSON.stringify(p)} -->` +
    el.join('') + '</svg>';
}

const out = join(dirname(fileURLToPath(import.meta.url)), '../../assets/patterns');
mkdirSync(out, { recursive: true });
const files = {
  'oqts-dots-uniform.svg': dots(RECIPE, 800, 800, { bottomFade: false }),
};
// ground tiles: one per seed, rotated per page so no two pages share a sky.
// 1204 = 86 cells x 14px, so the dot lattice crosses the seam intact.
for (let i = 0; i < SEEDS.length; i++) {
  files[`oqts-dots-ground-${i + 1}.svg`] = groundTile({ ...RECIPE, seed: SEEDS[i] }, 1204);
}
for (let i = 0; i < SEEDS.length; i++) {
  // right cut: anchored to the right edge of the 1120px content column, the
  // faintest dots land around the middle of the page (ramp 0.42 -> 0.97 of 1200px)
  files[`oqts-dots-right-${i + 1}.svg`] =
    dots({ ...RECIPE, seed: SEEDS[i] }, 1200, 760, { rampStart: 0.42, rampEnd: 0.97 });
}
for (const [name, svg] of Object.entries(files)) {
  writeFileSync(join(out, name), svg);
  console.log(name, (svg.length / 1024).toFixed(1) + 'k');
}
